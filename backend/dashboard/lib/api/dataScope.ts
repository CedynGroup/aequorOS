/**
 * WHAT A READER IS ACTUALLY LOOKING AT, when their access covers part of a book.
 *
 * Phase 4 gave `authorization_bindings` a data scope, and the backend honours it
 * everywhere: a branch- or region-scoped reader's rows, totals, pages, facets and
 * counts are all computed over their slice. The API says so — the three credit
 * payloads carry `data_scope`, and `/auth/me` carries one per capability. Until
 * this module existed nothing in the browser said so, so a scoped total was drawn
 * exactly as the institution's own book would be. This is the module that turns
 * that disclosure into a sentence.
 *
 * Everything here is PURE and has no transport: it takes a payload (or the
 * projected capabilities) and returns copy. Three rules it exists to keep:
 *
 * 1. NO ENUM REACHES THE SCREEN. `all`, `branch`, `region`, `mixed` and `none`
 *    are the evaluator's vocabulary, not words. A reader is told, in a sentence,
 *    that what they are looking at covers part of the institution and which part.
 * 2. FAIL CLOSED. If the coverage cannot be established — the payload did not
 *    state one, a capability row predates the column, two figures in one answer
 *    are covered differently — the figures are NOT presented as the
 *    institution's. `qualified` is true and the statement says the coverage is
 *    unknown. The only `qualified: false` answers are "the whole book" and
 *    "nothing governed is on screen yet".
 * 3. AN EMPTY ANSWER UNDER A NARROW SCOPE IS NOT AN EMPTY BOOK. `emptyMeaning`
 *    is the sentence an empty result has to carry instead of "this institution
 *    has none" — the same rule as the BI widgets' `needs_data`.
 *
 * BOTH WIRE SPELLINGS ARE READ, deliberately. `packages/risk-service-api/src` is
 * regenerated by hand, and its `<Model>FromJSON` opens with `...json` before it
 * overwrites the fields it knows — so a column the client has not been
 * regenerated against arrives under its snake_case wire name (`data_scope`,
 * `unresolved_regions`) and becomes camelCase the day it is regenerated. Reading
 * one spelling would make a branch-scoped total read as institution-wide on
 * exactly one side of that regeneration, which is the single most dangerous
 * direction this module can be wrong in.
 *
 * No currency, regulator or country literal appears here: a branch code is the
 * institution's own token and every sentence below is jurisdiction-neutral.
 */

import type { EffectiveCapabilityRead } from "@aequoros/risk-service-api";

/** One catalogue member's authorization address, as a reader's figures name it. */
export type ScopePair = Readonly<{ module: string; sensitivity: string }>;

/**
 * Every address the figures on one surface read, and whether that list is
 * COMPLETE.
 *
 * `complete: false` is the fail-closed input: a figure whose address could not be
 * resolved — an id the catalogue does not hold, a bank formula naming a figure
 * that is not in this reader's catalogue — means the coverage of what is on
 * screen cannot be established, and it must not be read as the whole book.
 */
export type FigureAddresses = Readonly<{
  pairs: readonly ScopePair[];
  complete: boolean;
}>;

/**
 * A scope exactly as a payload stated it. The `kind` is kept RAW and is never
 * rendered — it selects a sentence and nothing else.
 */
export type DeclaredScope = Readonly<{
  kind: string;
  branches: readonly string[];
  regions: readonly string[];
  /** Regions the institution's own register places no branch in. Credit only. */
  unresolvedRegions: readonly string[];
}>;

/**
 * How much of the institution's book the figures on one surface cover, with the
 * copy that says so.
 */
export type ReaderCoverage = Readonly<{
  /**
   * True whenever what is displayed is NOT known to be the institution's whole
   * book. It is the flag a surface must consult before drawing a figure as a
   * bank total, and it is true for "unknown" as well as for "narrowed".
   */
  qualified: boolean;
  /** True when the coverage is known AND nameable. False on every fail-closed path. */
  determined: boolean;
  /** True while the answer is still being loaded: render nothing yet, not a warning. */
  pending: boolean;
  /** The sentence beside the figures. Null only when there is nothing to say. */
  statement: string | null;
  /** Which branches or regions, when the payload named them. */
  detail: string | null;
  /** A grant to correct, rather than a book to report. */
  correction: string | null;
  /** The clause that qualifies one figure's own label, e.g. "in your branches". */
  suffix: string | null;
  /** The short line under a qualified figure. */
  hint: string | null;
  /** What an EMPTY answer means under this coverage — never "the book is empty". */
  emptyMeaning: string | null;
}>;

const BASE: ReaderCoverage = Object.freeze({
  qualified: false,
  determined: true,
  pending: false,
  statement: null,
  detail: null,
  correction: null,
  suffix: null,
  hint: null,
  emptyMeaning: null,
});

/** The institution's own book, in full. The only unqualified narrowing answer. */
export const WHOLE_BOOK: ReaderCoverage = BASE;

/**
 * Nothing governed is on screen yet — an Explore page with no figure chosen.
 * There is no figure to misrepresent, so nothing is said. Callers must pass the
 * members actually on screen; passing none while figures are drawn would be a
 * fail-open, which is why this constant is named for its precondition.
 */
export const NO_GOVERNED_FIGURES: ReaderCoverage = BASE;

/** Still loading. A surface renders no notice and no figure. */
export const COVERAGE_PENDING: ReaderCoverage = Object.freeze({
  ...BASE,
  qualified: true,
  determined: false,
  pending: true,
});

const UNKNOWN_STATEMENT =
  "How much of this institution's book these figures cover could not be established, " +
  "so they are not presented as the institution's own totals. Reload the page; if this " +
  "persists, ask your organization owner to check your access.";

/** The fail-closed answer: we could not establish the coverage. */
export const COVERAGE_UNDETERMINED: ReaderCoverage = Object.freeze({
  ...BASE,
  qualified: true,
  determined: false,
  statement: UNKNOWN_STATEMENT,
  suffix: "with coverage not established",
  hint: "Coverage not established",
  emptyMeaning:
    "Nothing was returned, and how much of the book was looked at could not be established — " +
    "so this is not a statement about what the institution holds.",
});

/** No grant covers these figures at all. */
export const COVERAGE_NONE: ReaderCoverage = Object.freeze({
  ...BASE,
  qualified: true,
  determined: false,
  statement:
    "Your access covers no part of this institution's book for these figures, so nothing " +
    "here is one of its totals. An organization owner can grant the coverage you need.",
  suffix: "with no coverage",
  hint: "No coverage",
  emptyMeaning:
    "Nothing was returned because your access covers no part of this book, which says " +
    "nothing about what the institution holds.",
});

/**
 * Two figures on one screen are covered differently.
 *
 * The server refuses such a question outright (`bi_data_scope_conflict`): two
 * narrow scopes have no ordering between them, so serving either would widen one
 * grant or silently drop half the other. The browser says the same thing before
 * the refusal arrives rather than after.
 */
export const COVERAGE_CONFLICTING: ReaderCoverage = Object.freeze({
  ...BASE,
  qualified: true,
  determined: false,
  statement:
    "Your access covers different parts of this institution's book for different figures " +
    "here, so they cannot be presented together as one set of totals. Ask your organization " +
    "owner for one coverage across these figures.",
  suffix: "with coverage that does not agree",
  hint: "Coverage does not agree across these figures",
  emptyMeaning:
    "Nothing was returned because the coverage of these figures does not agree, which says " +
    "nothing about what the institution holds.",
});

const QUALIFIED_OPENER = "You are seeing part of this institution's book.";

/**
 * How precisely a surface knows WHICH of its figures the coverage applies to.
 *
 * `exact` — the coverage was established for the figures actually on screen: a
 * payload that disclosed the scope it applied, or an address list resolved from
 * the very question that was asked. The sentence may speak about "these figures".
 *
 * `surface` — the coverage was established for the members a surface COULD read,
 * because the payload discloses none and the reader's grants are the only source.
 * The strongest true sentence is then that PART of the page is narrowed, without
 * claiming which part. Saying "these figures cover only your branches" here would
 * be a fabricated specific: an institution-wide module's figure on the same page
 * is not narrowed at all. Hedging is the honest direction, and it is still
 * qualified — the reader is never told a page is the institution's book.
 */
export type CoveragePrecision = "exact" | "surface";

function list(values: readonly string[]): string {
  if (values.length <= 4) return values.join(", ");
  return `${values.slice(0, 4).join(", ")} and ${values.length - 4} more`;
}

/** The one place a narrowed sentence is composed, for both precisions. */
function narrowedCoverage(
  precision: CoveragePrecision,
  slice: string,
  detail: string | null,
  suffix: string,
  emptyMeaning: string,
): ReaderCoverage {
  if (precision === "exact") {
    return {
      ...BASE,
      qualified: true,
      determined: true,
      statement: `${QUALIFIED_OPENER} These figures cover only ${slice}, so they are not the institution's own totals.`,
      detail,
      suffix,
      hint: "Part of this institution's book",
      emptyMeaning,
    };
  }
  return {
    ...BASE,
    qualified: true,
    determined: true,
    statement:
      `${QUALIFIED_OPENER} Some of what is shown here covers only ${slice}, so those ` +
      "figures are not the institution's own totals. This page does not say which of them.",
    detail,
    // Deliberately no per-figure clause: at this precision no individual figure
    // can be labelled as narrowed without inventing which one.
    suffix: null,
    hint: "Parts of this page cover part of this institution's book",
    emptyMeaning,
  };
}

function branchCoverage(
  scope: DeclaredScope,
  precision: CoveragePrecision,
): ReaderCoverage {
  return narrowedCoverage(
    precision,
    "the branches your access names",
    `Branches covered: ${list(scope.branches)}`,
    "in your branches",
    "Nothing was returned for the branches your access covers. The institution may hold " +
      "figures in branches outside your coverage.",
  );
}

function regionCoverage(
  scope: DeclaredScope,
  precision: CoveragePrecision,
): ReaderCoverage {
  const resolved =
    scope.branches.length > 0
      ? ` Branches in them: ${list(scope.branches)}.`
      : "";
  return narrowedCoverage(
    precision,
    "the regions your access names",
    `Regions covered: ${list(scope.regions)}.${resolved}`,
    "in your regions",
    "Nothing was returned for the regions your access covers. The institution may hold " +
      "figures in regions outside your coverage.",
  );
}

function mixedCoverage(
  scope: DeclaredScope,
  precision: CoveragePrecision,
): ReaderCoverage {
  const parts: string[] = [];
  if (scope.branches.length > 0) {
    parts.push(`branches ${list(scope.branches)}`);
  }
  if (scope.regions.length > 0) {
    parts.push(`regions ${list(scope.regions)}`);
  }
  return narrowedCoverage(
    precision,
    "the branches and regions your access names",
    parts.length > 0 ? `Covered: ${parts.join("; ")}` : null,
    "in your part of the book",
    "Nothing was returned for the part of the book your access covers. The institution " +
      "may hold figures outside your coverage.",
  );
}

/**
 * A region a grant names that the institution's own branch register places no
 * branch in. Zero rows for that reason is a grant to correct, not a book to
 * report, so it is said out loud on top of whichever sentence applies.
 */
function withCorrection(
  coverage: ReaderCoverage,
  unresolved: readonly string[],
): ReaderCoverage {
  if (unresolved.length === 0) return coverage;
  return {
    ...coverage,
    correction:
      `Your access names ${unresolved.length === 1 ? "a region" : "regions"} that no branch in ` +
      `this institution's register belongs to (${list(unresolved)}), so nothing from ` +
      `${unresolved.length === 1 ? "it" : "them"} is included. Ask your organization owner to ` +
      "correct the grant, or have the branch register updated.",
  };
}

function texts(value: unknown): readonly string[] {
  if (!Array.isArray(value)) return [];
  const seen = new Set<string>();
  for (const entry of value) {
    if (typeof entry !== "string") continue;
    const trimmed = entry.trim();
    if (trimmed.length > 0) seen.add(trimmed);
  }
  // Ordinal, and case PRESERVED: a branch code is the core banking system's own
  // token, and folding it would collide two genuinely different branches.
  return [...seen].sort();
}

function field(source: unknown, key: string): unknown {
  if (typeof source !== "object" || source === null) return undefined;
  return (source as Record<string, unknown>)[key];
}

/**
 * The scope a payload stated, in either wire spelling, or null when it stated
 * none. `null` is the fail-closed input to every function below — it is NOT the
 * whole book.
 */
export function readDeclaredScope(payload: unknown): DeclaredScope | null {
  const container = field(payload, "dataScope") ?? field(payload, "data_scope");
  const kind = field(container, "kind");
  if (typeof kind !== "string" || kind.trim().length === 0) return null;
  return {
    kind: kind.trim(),
    branches: texts(field(container, "branches")),
    regions: texts(field(container, "regions")),
    unresolvedRegions: texts(
      field(container, "unresolvedRegions") ??
        field(container, "unresolved_regions"),
    ),
  };
}

/**
 * The coverage one declared scope describes.
 *
 * A narrowing kind with no values is read as UNDETERMINED, not as the whole
 * book: the row is not the institution's book, and saying it is because the
 * shape is unfamiliar would overstate what is on screen. Same rule for a kind
 * this build does not know — a scope added to the server after this build
 * shipped must not silently read as "everything".
 */
export function coverageFromScope(
  scope: DeclaredScope | null,
  precision: CoveragePrecision = "exact",
): ReaderCoverage {
  if (scope === null) return COVERAGE_UNDETERMINED;
  if (scope.kind === "all") return WHOLE_BOOK;
  if (scope.kind === "none") return COVERAGE_NONE;
  if (scope.kind === "branch" && scope.branches.length > 0) {
    return withCorrection(
      branchCoverage(scope, precision),
      scope.unresolvedRegions,
    );
  }
  if (scope.kind === "region" && scope.regions.length > 0) {
    return withCorrection(
      regionCoverage(scope, precision),
      scope.unresolvedRegions,
    );
  }
  if (
    scope.kind === "mixed" &&
    scope.branches.length + scope.regions.length > 0
  ) {
    return withCorrection(
      mixedCoverage(scope, precision),
      scope.unresolvedRegions,
    );
  }
  return withCorrection(COVERAGE_UNDETERMINED, scope.unresolvedRegions);
}

/**
 * The coverage a response payload discloses about its OWN figures.
 *
 * This is the authoritative reading wherever it is available: the payload states
 * the scope the server actually applied to the rows and every count in it, so no
 * derivation can disagree with it.
 */
export function coverageFromPayload(
  payload: unknown,
  options: { pending?: boolean } = {},
): ReaderCoverage {
  if (options.pending === true) return COVERAGE_PENDING;
  if (payload === undefined || payload === null) return COVERAGE_PENDING;
  return coverageFromScope(readDeclaredScope(payload));
}

/** The canonical identity of a scope, for deciding whether two agree. */
function scopeKey(scope: DeclaredScope): string {
  return [scope.kind, scope.branches.join(","), scope.regions.join(",")].join(
    "|",
  );
}

/**
 * The coverage of figures whose own payload does not disclose one.
 *
 * The BI query, grid, insights and trust payloads carry no scope field even
 * though the server resolves and applies one, so the only honest source in the
 * browser is the projection on `/auth/me`: `EffectiveCapabilityRead.data_scope`
 * is reduced per (institution, module, sensitivity, permission), which is
 * exactly the address a catalogue member has.
 *
 * The reduction MIRRORS the server's own (`read_bi._merged_decision`): a
 * conjunctive read is served at its narrowest sentence, `all` is the universe so
 * any narrower pass wins over it, and two DIFFERENT narrow scopes have no
 * ordering between them — so that is refused rather than guessed at. Every other
 * unanswerable case falls to `COVERAGE_UNDETERMINED`, never to the whole book.
 *
 * `pairs` must be the members ACTUALLY on screen. An empty list means no
 * governed figure is drawn yet, which is why its answer is silent.
 */
export function coverageFromCapabilities(
  capabilities: readonly EffectiveCapabilityRead[] | undefined,
  pairs: readonly ScopePair[],
  options: {
    pending?: boolean;
    permission?: string;
    precision?: CoveragePrecision;
  } = {},
): ReaderCoverage {
  if (options.pending === true) return COVERAGE_PENDING;
  if (pairs.length === 0) return NO_GOVERNED_FIGURES;
  if (capabilities === undefined) return COVERAGE_UNDETERMINED;
  const permission = options.permission ?? "view";
  const narrow = new Map<string, DeclaredScope>();
  for (const pair of pairs) {
    const rows = capabilities.filter(
      (capability) =>
        capability.module === pair.module &&
        capability.sensitivity === pair.sensitivity &&
        capability.permission === permission,
    );
    // No row for a member that is on screen: the figure is being drawn without a
    // capability that explains it, so its coverage is not establishable.
    if (rows.length === 0) return COVERAGE_UNDETERMINED;
    for (const row of rows) {
      const scope = readDeclaredScope(row);
      // A projection that predates the data-scope column. Silence here would read
      // as the whole book for every scoped reader on an older backend.
      if (scope === null) return COVERAGE_UNDETERMINED;
      if (scope.kind === "none") return COVERAGE_NONE;
      if (scope.kind === "all") continue;
      narrow.set(scopeKey(scope), scope);
    }
  }
  // Sound at BOTH precisions: if every address is the universe, no figure drawn
  // from any of them is narrowed, whether or not we know which is on screen.
  if (narrow.size === 0) return WHOLE_BOOK;
  if (narrow.size > 1) return COVERAGE_CONFLICTING;
  return coverageFromScope(
    [...narrow.values()][0]!,
    options.precision ?? "exact",
  );
}

/**
 * The coverage of a surface whose figures were resolved to addresses elsewhere.
 *
 * The order is the whole point: a load still in flight says nothing, an
 * incomplete address list fails closed, and only a complete list is reduced.
 */
export function coverageForFigures(
  capabilities: readonly EffectiveCapabilityRead[] | undefined,
  addresses: FigureAddresses,
  options: {
    pending?: boolean;
    permission?: string;
    precision?: CoveragePrecision;
  } = {},
): ReaderCoverage {
  if (options.pending === true) return COVERAGE_PENDING;
  if (!addresses.complete) return COVERAGE_UNDETERMINED;
  return coverageFromCapabilities(capabilities, addresses.pairs, options);
}

/**
 * One figure's label, qualified so the number cannot read as the institution's.
 *
 * A clause on the label rather than a badge beside it: a badge is a thing a
 * reader can miss, and the number is what gets quoted into a board paper.
 */
export function coverageFigureLabel(
  wholeBookLabel: string,
  coverage: ReaderCoverage,
): string {
  if (!coverage.qualified || coverage.suffix === null) return wholeBookLabel;
  return `${wholeBookLabel} ${coverage.suffix}`;
}

/** Whether a surface should draw the coverage notice at all. */
export function showsCoverageNotice(coverage: ReaderCoverage): boolean {
  return coverage.qualified && !coverage.pending && coverage.statement !== null;
}
