/**
 * The reader-coverage sentences, in every state a scope can reach.
 *
 * Three properties carry this suite, and each one names a defect it exists to
 * prevent:
 *
 * 1. FAIL CLOSED. Every unanswerable input — a payload that states no scope, a
 *    narrowing kind with no values, a kind this build does not know, a
 *    capability row from a backend that predates the column, two figures covered
 *    differently — must come back `qualified`. The one direction an access
 *    display must never be wrong in is reading a slice as the whole book.
 * 2. BOTH WIRE SPELLINGS. `packages/risk-service-api/src` is regenerated by
 *    hand, so `data_scope` and `dataScope` are both live spellings of the same
 *    field, on opposite sides of one regeneration. A branch-scoped total must
 *    read identically either way.
 * 3. NO ENUM AND NO COUNTRY REACHES THE SCREEN. `all`/`branch`/`region`/
 *    `mixed`/`none` are the evaluator's vocabulary; a reader gets a sentence.
 *    And jurisdiction is data, so no currency, regulator or country literal may
 *    appear in copy that a non-Ghanaian tenant will also read.
 *
 * Run: pnpm --filter @aequoros/dashboard test
 */

import assert from "node:assert/strict";
import {
  COVERAGE_CONFLICTING,
  COVERAGE_NONE,
  COVERAGE_PENDING,
  COVERAGE_UNDETERMINED,
  WHOLE_BOOK,
  coverageFigureLabel,
  coverageForFigures,
  coverageFromCapabilities,
  coverageFromPayload,
  coverageFromScope,
  readDeclaredScope,
  showsCoverageNotice,
  type ReaderCoverage,
  type ScopePair,
} from "./dataScope";

// --- 1. readDeclaredScope reads both spellings ------------------------------

const SNAKE = {
  total: 412,
  data_scope: {
    kind: "branch",
    branches: ["TEM-002", " ACC-001 ", "ACC-001", ""],
    regions: [],
    unresolved_regions: ["Northern"],
  },
};

const CAMEL = {
  total: 412,
  dataScope: {
    kind: "branch",
    branches: ["TEM-002", " ACC-001 ", "ACC-001", ""],
    regions: [],
    unresolvedRegions: ["Northern"],
  },
};

for (const [name, payload] of [
  ["the wire spelling the client has not been regenerated against", SNAKE],
  ["the spelling the client emits once regenerated", CAMEL],
] as const) {
  const scope = readDeclaredScope(payload);
  assert.ok(scope, `${name}: the scope must be found`);
  assert.equal(scope.kind, "branch", name);
  assert.deepEqual(
    [...scope.branches],
    ["ACC-001", "TEM-002"],
    `${name}: trimmed, de-duplicated, ordered, case preserved`,
  );
  assert.deepEqual([...scope.unresolvedRegions], ["Northern"], name);
}

// The two spellings must produce the SAME sentence, or a scoped total reads as
// institution-wide on exactly one side of the client regeneration.
assert.deepEqual(
  coverageFromPayload(SNAKE),
  coverageFromPayload(CAMEL),
  "both wire spellings must produce identical copy",
);

assert.equal(
  readDeclaredScope({ total: 1 }),
  null,
  "a payload that states no scope states none — never the whole book",
);
assert.equal(
  readDeclaredScope({ data_scope: { kind: "   " } }),
  null,
  "a blank kind is no statement at all",
);
assert.deepEqual(
  [
    ...readDeclaredScope({ data_scope: { kind: "branch", branches: "ACC" } })!
      .branches,
  ],
  [],
  "a non-array value yields no values rather than a coerced one",
);
assert.deepEqual(
  [
    ...readDeclaredScope({
      data_scope: { kind: "branch", branches: ["b", "B", "a"] },
    })!.branches,
  ],
  ["B", "a", "b"],
  "case is preserved: folding it would collide two different branch codes",
);

// --- 2. every state, and the fail-closed floor -----------------------------

assert.equal(
  coverageFromScope({
    kind: "all",
    branches: [],
    regions: [],
    unresolvedRegions: [],
  }).qualified,
  false,
  "the whole book is the one narrowing answer that is not qualified",
);

const branch = coverageFromScope({
  kind: "branch",
  branches: ["ACC-001", "TEM-002"],
  regions: [],
  unresolvedRegions: [],
});
assert.equal(branch.qualified, true);
assert.equal(branch.determined, true);
assert.match(branch.statement!, /part of this institution's book/);
assert.match(branch.detail!, /ACC-001/);
assert.match(branch.detail!, /TEM-002/);
assert.equal(branch.correction, null);
assert.ok(
  branch.emptyMeaning,
  "an empty answer under a scope needs its meaning",
);

const region = coverageFromScope({
  kind: "region",
  branches: ["ACC-001"],
  regions: ["Coastal"],
  unresolvedRegions: [],
});
assert.equal(region.qualified, true);
assert.match(region.detail!, /Coastal/);
assert.match(
  region.detail!,
  /ACC-001/,
  "a region grant resolves to branch codes; naming them is the honest detail",
);

const mixed = coverageFromScope({
  kind: "mixed",
  branches: ["ACC-001"],
  regions: ["Coastal"],
  unresolvedRegions: [],
});
assert.equal(mixed.qualified, true);
assert.match(mixed.detail!, /ACC-001/);
assert.match(mixed.detail!, /Coastal/);

const unresolved = coverageFromScope({
  kind: "region",
  branches: [],
  regions: ["Coastal", "Northern"],
  unresolvedRegions: ["Northern"],
});
assert.ok(
  unresolved.correction,
  "a region no branch belongs to is a grant to correct, not a book to report",
);
assert.match(unresolved.correction!, /Northern/);

// The fail-closed floor. Each of these was, in an earlier draft of this feature,
// a plausible place to return the whole book.
const FAIL_CLOSED: readonly [string, ReaderCoverage][] = [
  ["a payload that stated no scope", coverageFromScope(null)],
  [
    "a narrowing kind carrying no values",
    coverageFromScope({
      kind: "branch",
      branches: [],
      regions: [],
      unresolvedRegions: [],
    }),
  ],
  [
    "a kind this build does not know",
    coverageFromScope({
      kind: "business_line",
      branches: ["X"],
      regions: [],
      unresolvedRegions: [],
    }),
  ],
  [
    "a region kind carrying only branches",
    coverageFromScope({
      kind: "region",
      branches: ["ACC-001"],
      regions: [],
      unresolvedRegions: [],
    }),
  ],
];
for (const [name, coverage] of FAIL_CLOSED) {
  assert.equal(coverage.qualified, true, `${name} must stay qualified`);
  assert.equal(coverage.determined, false, `${name} must not claim to know`);
  assert.equal(coverage.pending, false, `${name} is an answer, not a wait`);
  assert.ok(coverage.statement, `${name} must say something`);
  assert.ok(
    showsCoverageNotice(coverage),
    `${name} must reach the reader's screen`,
  );
}

// A kind that names no coverage at all, and an unfamiliar kind that also names
// an unresolvable region, still carries the correction.
assert.ok(
  coverageFromScope({
    kind: "business_line",
    branches: [],
    regions: [],
    unresolvedRegions: ["Northern"],
  }).correction,
);

assert.equal(
  coverageFromScope({
    kind: "none",
    branches: [],
    regions: [],
    unresolvedRegions: [],
  }),
  COVERAGE_NONE,
);

// --- 3. pending is a wait, not a warning -----------------------------------

assert.equal(coverageFromPayload(undefined), COVERAGE_PENDING);
assert.equal(coverageFromPayload(null), COVERAGE_PENDING);
assert.equal(coverageFromPayload(SNAKE, { pending: true }), COVERAGE_PENDING);
assert.equal(
  showsCoverageNotice(COVERAGE_PENDING),
  false,
  "a load in flight must not flash an access warning",
);
assert.equal(
  COVERAGE_PENDING.qualified,
  true,
  "while loading, nothing may be drawn as the institution's own figure",
);

// --- 4. the capability projection, reduced the way the server reduces it ----

type Capability = {
  module: string;
  sensitivity: string;
  permission: string;
  requiresContextualAuthorization: boolean;
  data_scope?: unknown;
  dataScope?: unknown;
};

function cap(
  module: string,
  sensitivity: string,
  scope: unknown,
  permission = "view",
  spelling: "snake" | "camel" = "snake",
): Capability {
  const row: Capability = {
    module,
    sensitivity,
    permission,
    requiresContextualAuthorization: false,
  };
  if (spelling === "snake") row.data_scope = scope;
  else row.dataScope = scope;
  return row;
}

const ALL_SCOPE = { kind: "all", branches: [], regions: [] };
const ACC = { kind: "branch", branches: ["ACC-001"], regions: [] };
const TEM = { kind: "branch", branches: ["TEM-002"], regions: [] };

const CREDIT: ScopePair = { module: "credit", sensitivity: "aggregated" };
const LIQ: ScopePair = { module: "liq", sensitivity: "aggregated" };

function capabilities(...rows: Capability[]) {
  // The projected rows as the surface holds them; the generated client's own
  // interface is narrower than the wire, which is the whole reason this module
  // reads unknown fields rather than typed ones.
  return rows as unknown as Parameters<typeof coverageFromCapabilities>[0];
}

assert.equal(
  coverageFromCapabilities(capabilities(), [], { pending: true }),
  COVERAGE_PENDING,
);
assert.equal(
  coverageFromCapabilities(capabilities(cap("credit", "aggregated", ACC)), [])
    .qualified,
  false,
  "no governed figure on screen is nothing to qualify",
);
assert.equal(
  coverageFromCapabilities(undefined, [CREDIT]),
  COVERAGE_UNDETERMINED,
  "figures on screen with no projection loaded must not read as the book",
);
assert.equal(
  coverageFromCapabilities(
    capabilities(cap("credit", "aggregated", ALL_SCOPE)),
    [CREDIT],
  ).qualified,
  false,
);
assert.deepEqual(
  coverageFromCapabilities(capabilities(cap("credit", "aggregated", ACC)), [
    CREDIT,
  ]),
  coverageFromScope({
    kind: "branch",
    branches: ["ACC-001"],
    regions: [],
    unresolvedRegions: [],
  }),
  "one narrow scope is the coverage, stated in full",
);
assert.equal(
  coverageFromCapabilities(
    capabilities(
      cap("credit", "aggregated", ACC),
      cap("liq", "aggregated", ALL_SCOPE),
    ),
    [CREDIT, LIQ],
  ).determined,
  true,
  "the narrowest sentence wins over the universe, exactly as the server merges",
);
assert.equal(
  coverageFromCapabilities(
    capabilities(
      cap("credit", "aggregated", ACC),
      cap("liq", "aggregated", TEM),
    ),
    [CREDIT, LIQ],
  ),
  COVERAGE_CONFLICTING,
  "two narrow scopes have no ordering; the server refuses and so does the copy",
);
assert.equal(
  coverageFromCapabilities(
    capabilities(
      cap("credit", "aggregated", ACC),
      cap("liq", "aggregated", { ...ACC }),
    ),
    [CREDIT, LIQ],
  ).determined,
  true,
  "the same scope twice is one coverage, not a conflict",
);
assert.equal(
  coverageFromCapabilities(capabilities(cap("liq", "aggregated", ALL_SCOPE)), [
    CREDIT,
  ]),
  COVERAGE_UNDETERMINED,
  "a figure with no capability row of its own cannot be explained",
);
assert.equal(
  coverageFromCapabilities(
    capabilities({
      module: "credit",
      sensitivity: "aggregated",
      permission: "view",
      requiresContextualAuthorization: false,
    }),
    [CREDIT],
  ),
  COVERAGE_UNDETERMINED,
  "a projection predating the column must not read as the whole book",
);
assert.equal(
  coverageFromCapabilities(
    capabilities(
      cap("credit", "aggregated", { kind: "none", branches: [], regions: [] }),
    ),
    [CREDIT],
  ),
  COVERAGE_NONE,
);
assert.deepEqual(
  coverageFromCapabilities(
    capabilities(cap("credit", "aggregated", ACC, "view", "camel")),
    [CREDIT],
  ),
  coverageFromCapabilities(
    capabilities(cap("credit", "aggregated", ACC, "view", "snake")),
    [CREDIT],
  ),
  "the projection's two spellings must produce identical copy too",
);
assert.equal(
  coverageFromCapabilities(
    capabilities(cap("credit", "aggregated", ALL_SCOPE, "export")),
    [CREDIT],
  ),
  COVERAGE_UNDETERMINED,
  "an unrelated permission's row does not explain a figure being viewed",
);

// --- 4b. the surface precision hedges rather than inventing a specific -----
//
// A payload that discloses no scope (BI query, grid, insights, trust) leaves the
// reader's own grants as the only source. Those describe what the surface COULD
// read, not what is on it, so the statement may not claim "these figures" —
// while still never reading as the institution's whole book.

const surfaceNarrow = coverageFromCapabilities(
  capabilities(
    cap("credit", "aggregated", ACC),
    cap("liq", "aggregated", ALL_SCOPE),
  ),
  [CREDIT, LIQ],
  { precision: "surface" },
);
assert.equal(surfaceNarrow.qualified, true);
assert.equal(surfaceNarrow.determined, true);
assert.match(surfaceNarrow.statement!, /Some of what is shown here/);
assert.match(
  surfaceNarrow.statement!,
  /does not say which/,
  "the hedge has to be explicit, or a reader reads it as covering everything",
);
assert.match(surfaceNarrow.detail!, /ACC-001/);
assert.equal(
  surfaceNarrow.suffix,
  null,
  "no individual figure may be labelled narrowed when which one is unknown",
);
assert.equal(
  coverageFigureLabel("Gross loans", surfaceNarrow),
  "Gross loans",
  "and the label is therefore left alone",
);
assert.notEqual(
  surfaceNarrow.statement,
  coverageFromCapabilities(
    capabilities(
      cap("credit", "aggregated", ACC),
      cap("liq", "aggregated", ALL_SCOPE),
    ),
    [CREDIT, LIQ],
    { precision: "exact" },
  ).statement,
  "the two precisions must not make the same claim",
);
assert.equal(
  coverageFromCapabilities(
    capabilities(
      cap("credit", "aggregated", ALL_SCOPE),
      cap("liq", "aggregated", ALL_SCOPE),
    ),
    [CREDIT, LIQ],
    { precision: "surface" },
  ).qualified,
  false,
  "every address being the universe is sound at either precision: nothing is narrowed",
);
for (const precision of ["exact", "surface"] as const) {
  assert.equal(
    coverageFromCapabilities(undefined, [CREDIT], { precision }),
    COVERAGE_UNDETERMINED,
    `${precision}: the fail-closed floor does not move with precision`,
  );
  assert.equal(
    coverageFromCapabilities(
      capabilities(
        cap("credit", "aggregated", ACC),
        cap("liq", "aggregated", TEM),
      ),
      [CREDIT, LIQ],
      { precision },
    ),
    COVERAGE_CONFLICTING,
    `${precision}: disagreeing coverage is refused at either precision`,
  );
}

// --- 4c. coverageForFigures orders pending, incomplete and reduced ----------

assert.equal(
  coverageForFigures(
    capabilities(cap("credit", "aggregated", ALL_SCOPE)),
    { pairs: [CREDIT], complete: true },
    { pending: true },
  ),
  COVERAGE_PENDING,
  "a load in flight wins over everything",
);
assert.equal(
  coverageForFigures(capabilities(cap("credit", "aggregated", ALL_SCOPE)), {
    pairs: [CREDIT],
    complete: false,
  }),
  COVERAGE_UNDETERMINED,
  "an unresolved figure must not be described by the coverage of the resolved ones",
);
assert.equal(
  coverageForFigures(capabilities(cap("credit", "aggregated", ALL_SCOPE)), {
    pairs: [],
    complete: true,
  }).qualified,
  false,
  "a question with no figure has nothing to qualify",
);
assert.deepEqual(
  coverageForFigures(capabilities(cap("credit", "aggregated", ACC)), {
    pairs: [CREDIT],
    complete: true,
  }),
  coverageFromCapabilities(capabilities(cap("credit", "aggregated", ACC)), [
    CREDIT,
  ]),
  "a complete list reduces exactly as the pairs would",
);

// --- 5. the figure label carries the qualification -------------------------

assert.equal(coverageFigureLabel("Loans on book", WHOLE_BOOK), "Loans on book");
for (const [name, coverage] of [
  ["a branch scope", branch],
  ["a region scope", region],
  ["a mixed scope", mixed],
  ["an undeterminable coverage", COVERAGE_UNDETERMINED],
  ["no coverage", COVERAGE_NONE],
  ["a disagreeing coverage", COVERAGE_CONFLICTING],
] as const) {
  const label = coverageFigureLabel("Loans on book", coverage);
  assert.notEqual(
    label,
    "Loans on book",
    `${name}: the figure's own label must say the figure is not the book's`,
  );
  assert.match(label, /^Loans on book /, name);
}
assert.equal(
  coverageFigureLabel("Loans on book", COVERAGE_PENDING),
  "Loans on book",
  "a load in flight does not rewrite a label; no figure is drawn yet",
);

// --- 6. no enum, and no country, reaches the screen ------------------------

const EVERY_STATE: readonly [string, ReaderCoverage][] = [
  ["whole book", WHOLE_BOOK],
  ["branch", branch],
  ["region", region],
  ["mixed", mixed],
  ["unresolved region", unresolved],
  ["undetermined", COVERAGE_UNDETERMINED],
  ["none", COVERAGE_NONE],
  ["conflicting", COVERAGE_CONFLICTING],
  ["pending", COVERAGE_PENDING],
  ["surface branch", surfaceNarrow],
  [
    "surface region",
    coverageFromScope(
      {
        kind: "region",
        branches: ["ACC-001"],
        regions: ["Coastal"],
        unresolvedRegions: ["Northern"],
      },
      "surface",
    ),
  ],
  [
    "surface mixed",
    coverageFromScope(
      {
        kind: "mixed",
        branches: ["ACC-001"],
        regions: ["Coastal"],
        unresolvedRegions: [],
      },
      "surface",
    ),
  ],
];

/** The evaluator's own vocabulary. A reader gets a sentence, never one of these. */
const WIRE_VALUES = ["all", "branch", "region", "mixed", "none"];

/**
 * Jurisdiction is data (AGENTS.md). Coverage copy is read by every tenant, so a
 * currency, regulator or country literal here would mislabel a non-Ghanaian one.
 */
const COUNTRY_LITERALS = [
  /\bGHS\b/,
  /\bBoG\b/,
  /Bank of Ghana/i,
  /\bGhana\b/i,
  /\bNGN\b/,
  /\bKES\b/,
  /\bZAR\b/,
  /\bcedi/i,
];

for (const [name, coverage] of EVERY_STATE) {
  const strings = [
    coverage.statement,
    coverage.detail,
    coverage.correction,
    coverage.suffix,
    coverage.hint,
    coverage.emptyMeaning,
  ].filter((value): value is string => typeof value === "string");
  for (const text of strings) {
    for (const value of WIRE_VALUES) {
      assert.notEqual(
        text.trim(),
        value,
        `${name}: rendered the wire value ${value} as copy`,
      );
      // The shapes a raw value takes when it leaks: quoted, parenthesised, or
      // after a colon. The English nouns "branches"/"regions" are deliberately
      // NOT caught by these — they are the words the Members composer uses too.
      for (const shape of [
        new RegExp(`["'\`]${value}["'\`]`),
        new RegExp(`\\(${value}\\)`),
        new RegExp(`:\\s*${value}\\b`),
      ]) {
        assert.ok(
          !shape.test(text),
          `${name}: the wire value ${value} leaked into copy: ${text}`,
        );
      }
    }
    for (const literal of COUNTRY_LITERALS) {
      assert.ok(
        !literal.test(text),
        `${name}: a jurisdiction literal reached coverage copy: ${text}`,
      );
    }
  }
  // Every sentence is a sentence: more than one word, capitalised, terminated.
  for (const sentence of [
    coverage.statement,
    coverage.correction,
    coverage.emptyMeaning,
  ]) {
    if (sentence === null) continue;
    assert.match(sentence, /^[A-Z]/, `${name}: a sentence starts capitalised`);
    assert.match(sentence, /[.]$/, `${name}: a sentence is terminated`);
    assert.ok(
      sentence.split(" ").length >= 8,
      `${name}: a one-word answer is a vocabulary, not copy`,
    );
  }
}

// A scoped statement must not be able to read as the institution's own figure.
for (const [name, coverage] of EVERY_STATE) {
  if (!coverage.qualified || coverage.pending) continue;
  const DENIALS = [
    /not the institution's own totals\. This page does not say which of them\./,
    /not the institution's own totals/,
    /not presented as the institution's own totals/,
    /nothing here is one of its totals/,
    /cannot be presented together as one set of totals/,
  ];
  assert.ok(
    DENIALS.some((denial) => denial.test(coverage.statement!)),
    `${name}: the statement must deny that these are the institution's totals`,
  );
}

// The positive half: each determinable state names its own coverage in words.
assert.match(branch.statement!, /branches/);
assert.match(region.statement!, /regions/);
assert.match(mixed.statement!, /branches and regions/);
assert.match(surfaceNarrow.statement!, /branches/);

console.log(
  `dataScope.test.ts: ${EVERY_STATE.length} coverage states, both wire spellings, the ` +
    `${FAIL_CLOSED.length} fail-closed inputs and the server's own merge rule all hold.`,
);
