"""Load the committed official-template layouts (``layouts/<FORM>.json``).

Regenerated by ``scripts/extract_bog_templates.py`` from ``docs/reporting``; the
runtime only reads them.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from functools import cache
from pathlib import Path
from typing import Any

from openpyxl.utils.cell import column_index_from_string, coordinate_from_string

LAYOUT_DIR = Path(__file__).parent / "layouts"


@dataclass(frozen=True)
class LayoutCell:
    ref: str
    kind: str  # label | input | formula
    value: Any = None
    formula: str | None = None
    bold: bool = False
    number_format: str | None = None
    align: str | None = None

    @property
    def row(self) -> int:
        return coordinate_from_string(self.ref)[1]

    @property
    def col(self) -> int:
        return column_index_from_string(coordinate_from_string(self.ref)[0])


@dataclass(frozen=True)
class SheetLayout:
    name: str
    max_row: int
    max_col: int
    column_widths: dict[str, float]
    merges: tuple[str, ...]
    cells: tuple[LayoutCell, ...]
    by_ref: dict[str, LayoutCell] = field(default_factory=dict, repr=False)

    def label_for_row(self, row: int) -> str:
        """The row's left-most label text (the BoG line description)."""
        candidates = [c for c in self.cells if c.row == row and c.kind == "label"]
        candidates.sort(key=lambda c: c.col)
        return str(candidates[0].value).strip() if candidates else ""

    @property
    def input_cells(self) -> tuple[LayoutCell, ...]:
        return tuple(c for c in self.cells if c.kind == "input")

    @property
    def formula_cells(self) -> tuple[LayoutCell, ...]:
        return tuple(c for c in self.cells if c.kind == "formula")


@dataclass(frozen=True)
class FormLayout:
    form: str
    workbook: str
    sheets: tuple[SheetLayout, ...]

    def sheet(self, name: str) -> SheetLayout:
        for sheet in self.sheets:
            if sheet.name == name:
                return sheet
        msg = f"{self.form}: no sheet named {name!r} (have {[s.name for s in self.sheets]})"
        raise KeyError(msg)

    @property
    def sheet_names(self) -> tuple[str, ...]:
        return tuple(s.name for s in self.sheets)


def _parse_sheet(raw: dict[str, Any]) -> SheetLayout:
    cells = tuple(
        LayoutCell(
            ref=c["ref"],
            kind=c["kind"],
            value=c.get("value"),
            formula=c.get("formula"),
            bold=bool(c.get("bold", False)),
            number_format=c.get("number_format"),
            align=c.get("align"),
        )
        for c in raw["cells"]
    )
    return SheetLayout(
        name=raw["name"],
        max_row=int(raw["max_row"]),
        max_col=int(raw["max_col"]),
        column_widths={k: float(v) for k, v in raw.get("column_widths", {}).items()},
        merges=tuple(raw.get("merges", [])),
        cells=cells,
        by_ref={c.ref: c for c in cells},
    )


@cache
def load_layout(form: str) -> FormLayout:
    path = LAYOUT_DIR / f"{form}.json"
    if not path.exists():
        msg = f"no committed layout for form {form!r} at {path}"
        raise FileNotFoundError(msg)
    raw = json.loads(path.read_text())
    return FormLayout(
        form=raw["form"],
        workbook=raw["workbook"],
        sheets=tuple(_parse_sheet(s) for s in raw["sheets"]),
    )


def available_layouts() -> tuple[str, ...]:
    return tuple(sorted(p.stem for p in LAYOUT_DIR.glob("*.json")))
